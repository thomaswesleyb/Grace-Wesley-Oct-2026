import type { Topic } from "@content/qa.ts";

/** Shape of content/details.json, generated from DETAILS.md by scripts/gen-content.ts. */
export interface SiteContent {
  brideShort: string;
  groomShort: string;
  brideFormal: string;
  groomFormal: string;
  dateText: string;
  timeText: string;
  ceremonyVenue: string;
  ceremonyCityState: string;
  ceremonyAddress: string | null;
  mapUrl: string;
  website: string;
  /** ISO instant of the ceremony start; null until the time zone is in DETAILS.md. */
  startsAt: string | null;
  contact: string;
  /** "Registry intro" from DETAILS.md; the registry page omits the intro until it's set. */
  registryIntro: string | null;
  /** "Photos intro" and "Labyrinth intro" from DETAILS.md; each page omits its intro until set. */
  photosIntro: string | null;
  labyrinthIntro: string | null;
  qa: { topic: Topic; question: string; answer: string }[];
}

/** One photo in content/gallery.json, generated by scripts/gen-gallery.ts. */
export interface GalleryPhoto {
  alt: string;
  caption: string | null;
  /** The large copy, up to 1600 px on its long side; `width` and `height` are its size. */
  src: string;
  width: number;
  height: number;
  /** A copy up to 800 px wide (the same file as `src` when the original is that small). */
  small: { src: string; width: number };
}
